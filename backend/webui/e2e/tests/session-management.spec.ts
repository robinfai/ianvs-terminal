import { test, expect } from '@playwright/test'
import { requireEnv } from './env'

const url = requireEnv('WEBUI_REMOTE_URL')
test('full account can explicitly replace a session and revoke others', async ({ page }, testInfo) => {
  test.skip(!process.env.WEBUI_SESSION_DB, 'Requires a pre-seeded isolated SQLite fixture; see backend/README.md')
  await page.goto(url)
  await page.getByLabel('用户名').fill('capacity-ui')
  await page.getByLabel('密码', { exact: false }).fill('session-ui-password')
  await page.getByLabel('此会话的设备备注').fill('Work MacBook · Chrome')
  await page.getByRole('button', { name: '登录账户', exact: true }).click()
  await expect(page.getByRole('button', { name: '处理已满的登录名额' })).toBeVisible()
  await page.getByRole('button', { name: '处理已满的登录名额' }).click()
  const replaceDialog = page.getByRole('dialog', { name: '退出最早会话并登录？' })
  await expect(replaceDialog).toContainText('最早待完成登录')
  await replaceDialog.getByRole('button', { name: '退出最早会话并登录', exact: true }).click()
  await expect(page.getByRole('heading', { name: '配置有序，连接安心' })).toBeVisible()
  await page.getByRole('link', { name: '安全与会话', exact: true }).click()
  const current = page.locator('.session-row').filter({ hasText: 'Work MacBook · Chrome' })
  await expect(current).toContainText('当前会话')
  await expect(page.getByRole('button', { name: '撤销此会话', exact: true })).toHaveCount(7)
  await page.screenshot({ path: testInfo.outputPath('sessions-desktop.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: testInfo.outputPath('sessions-mobile.png'), fullPage: true })
  await page.getByRole('button', { name: '退出其他会话', exact: true }).click()
  const revokeDialog = page.getByRole('dialog', { name: '确认撤销 7 个会话？' })
  await expect(revokeDialog).toContainText('不会远程删除已下载的数据')
  await revokeDialog.getByRole('button', { name: '确认撤销', exact: true }).click()
  await expect(page.getByRole('button', { name: '撤销此会话', exact: true })).toHaveCount(0)
  await expect(current).toContainText('当前会话')
  await expect(page.getByRole('status')).toContainText('已确认撤销 7 / 7 个会话')
  await page.getByRole('button', { name: '退出当前账户', exact: true }).click()
  await page.getByRole('dialog', { name: '确认退出当前会话？' }).getByRole('button', { name: '确认退出', exact: true }).click()
  await expect(page.getByRole('heading', { name: '登录 Ianvs' })).toBeVisible()
})
